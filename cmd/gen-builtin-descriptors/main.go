// gen-builtin-descriptors writes runtime/pb/descriptors_builtin.lua: the
// serialized FileDescriptorProto of every file the runtime ships a
// descriptor for (well-known types, descriptor.proto, plugin.proto and
// google/api/{annotations,http}.proto), taken from protobuf-go's
// registry. pb.descriptors loads the table on first use, so server
// reflection can hand these files to clients like any generated one.
//
// Usage:
//
//	go run ./cmd/gen-builtin-descriptors > runtime/pb/descriptors_builtin.lua
package main

import (
	"bufio"
	"fmt"
	"os"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"

	"github.com/tarantool-contrib/tarantool-protobuf/internal/builtindesc"
	"github.com/tarantool-contrib/tarantool-protobuf/internal/luastr"
)

func main() {
	w := bufio.NewWriter(os.Stdout)
	if err := run(w); err != nil {
		fmt.Fprintf(os.Stderr, "gen-builtin-descriptors: %v\n", err)
		os.Exit(1)
	}
	if err := w.Flush(); err != nil {
		fmt.Fprintf(os.Stderr, "gen-builtin-descriptors: %v\n", err)
		os.Exit(1)
	}
}

func run(w *bufio.Writer) error {
	p := func(format string, args ...any) { fmt.Fprintf(w, format+"\n", args...) }
	p("-- Code generated by gen-builtin-descriptors. DO NOT EDIT.")
	p("--")
	p("-- Serialized FileDescriptorProto (source_code_info stripped) of every")
	p("-- file whose descriptor the runtime ships: the well-known types,")
	p("-- descriptor.proto, plugin.proto and google/api/{annotations,http}.proto.")
	p("-- Dependencies come before the files that import them. Loaded lazily")
	p("-- by pb.descriptors; regenerate with `just gen-builtin-descriptors`.")
	p("return {")
	for _, fd := range builtindesc.Files() {
		fdp := protodesc.ToFileDescriptorProto(fd)
		fdp.SourceCodeInfo = nil
		b, err := proto.MarshalOptions{Deterministic: true}.Marshal(fdp)
		if err != nil {
			return fmt.Errorf("%s: %w", fd.Path(), err)
		}
		p("    {")
		p("        name = %s,", luastr.Literal(fd.Path()))
		p("        bytes = table.concat({")
		for _, chunk := range luastr.Chunks(b) {
			p("            %s,", chunk)
		}
		p("        }),")
		p("    },")
	}
	p("}")
	return nil
}
